CREATE TABLE IF NOT EXISTS public.users (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    current_balance NUMERIC(14,2) NOT NULL DEFAULT 0.00,
    monthly_income NUMERIC(14,2) NOT NULL DEFAULT 0.00,
    invested_patrimony NUMERIC(14,2) NOT NULL DEFAULT 0.00,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.transactions (
    id BIGINT PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    type TEXT NOT NULL,
    amount NUMERIC(14,2) NOT NULL,
    description TEXT NOT NULL,
    category TEXT NOT NULL,
    subcategory TEXT,
    necessity TEXT NOT NULL,
    transaction_date TEXT NOT NULL,
    due_date TEXT,
    payment_method TEXT DEFAULT 'pix',
    source_account TEXT,
    destination_account TEXT,
    card_name TEXT,
    installments INTEGER DEFAULT 1,
    installment_number INTEGER DEFAULT 1,
    parent_tx_id BIGINT,
    recurrence TEXT,
    person_involved TEXT,
    status TEXT NOT NULL DEFAULT 'confirmed',
    dedup_hash TEXT,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.goals (
    id BIGINT PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    target_amount NUMERIC(14,2) NOT NULL,
    saved_amount NUMERIC(14,2) NOT NULL DEFAULT 0.00,
    deadline_months INTEGER NOT NULL DEFAULT 24,
    category_icon TEXT NOT NULL DEFAULT '🏍️',
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    action TEXT NOT NULL,
    target_tx_id BIGINT,
    before_json TEXT,
    after_json TEXT,
    created_at TEXT NOT NULL
);

-- Libera acesso para a chave anon/publishable sincronizar sem bloqueio de RLS
ALTER TABLE public.users DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.transactions DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.goals DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_log DISABLE ROW LEVEL SECURITY;

GRANT ALL ON TABLE public.users TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.transactions TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.goals TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.audit_log TO anon, authenticated, service_role;

